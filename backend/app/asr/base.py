"""Базовый интерфейс ASR — провайдер-агностичный слой.

Меняя реализацию (faster-whisper, NeMo/Riva на боевом сервере, облако),
остальной код не трогаем.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

import numpy as np


@dataclass
class ASRWord:
    text: str
    start: float
    end: float
    prob: float = 1.0


@dataclass
class ASRResult:
    text: str
    words: list[ASRWord] = field(default_factory=list)
    language: str = "ru"


def _normalize_word(w: str) -> str:
    return w.strip(" .,!?;:—-\"'«»").lower()


def has_repeating_ngram(text: str, max_n: int = 4, min_repeats: int = 3) -> bool:
    """True, если в тексте одно и то же слово/короткая фраза (1-4 слова) повторяется подряд
    `min_repeats` раз и более — надёжный признак типичной галлюцинации Whisper на коротких/
    шумных клипах («Ветка. Ветка. Ветка...», «я не знаю, я не знаю, я не знаю...»). Проверено на
    реальных примерах из живых записей — обычная речь так не повторяется, а зацикленное
    декодирование почти всегда именно так и выглядит, даже при включённых
    temperature-fallback/compression_ratio_threshold (см. faster_whisper_provider.py — та
    настройка снижает частоту, но не устраняет полностью на очень коротких клипах)."""
    words = [_normalize_word(w) for w in text.split()]
    words = [w for w in words if w]
    n_words = len(words)
    for n in range(1, max_n + 1):
        if n_words < n * min_repeats:
            continue
        i = 0
        while i + n * 2 <= n_words:
            chunk = words[i:i + n]
            repeats = 1
            j = i + n
            while j + n <= n_words and words[j:j + n] == chunk:
                repeats += 1
                j += n
            if repeats >= min_repeats:
                return True
            i += 1
    return False


# Заученные «титровые» галлюцинации. Whisper обучался в том числе на субтитрах YouTube и на
# не-речи уверенно выдаёт запомненные подписи авторов. Ловятся они только по тексту: уверенность
# у них ВЫСОКАЯ (модель не «сомневается»), поэтому ни logprob-порог, ни no_speech_threshold их
# не отсеивают, а повтора внутри сегмента нет — has_repeating_ngram тоже мимо.
# Наблюдались на реальных записях этого проекта: «Редактор субтитров А.Синецкая Корректор
# А.Егорова», «Редактор субтитров И.Бойкова», «Субтитры сделал DimaTorzok», «Продолжение следует».
_CREDIT_MARKERS = (
    "субтитр",          # «субтитры сделал…», «редактор субтитров…»
    "продолжение следует",
    "спасибо за просмотр",
    "подписывайтесь на канал",
)

# «Корректор» — единственный маркер, который сам по себе НЕ титровый: это обычная профессия, и
# в биографическом блоке допроса «Он работал корректором в типографии» (5 слов) гейт длины
# пропускал прямо в фильтр. Поэтому требуем титрового окружения: соседний «редактор»/«субтитр»
# либо подпись инициалами («А.Егорова», «И .Бойкова» — пробел перед точкой встречается в
# реальных распознаваниях).
_INITIALS_RE = re.compile(r"\b[а-яёa-z]\s*\.\s*[а-яёa-z]", re.IGNORECASE)


def looks_like_known_hallucination(text: str) -> bool:
    """True для заученных титровых фраз. Намеренно узко: слово должно встретиться в коротком
    сегменте (титры — это весь «распознанный» текст, а не вставка в живую реплику), иначе
    настоящая реплика со словом «субтитры» была бы выброшена. Гейта длины для этого мало —
    маркеры-профессии («корректор») в короткую живую реплику помещаются свободно, поэтому им
    нужен ещё и титровый контекст (см. `_INITIALS_RE`)."""
    low = text.lower()
    if len(text.split()) > 8:
        return False
    if any(m in low for m in _CREDIT_MARKERS):
        return True
    return ("корректор" in low
            and ("редактор" in low or "субтитр" in low or bool(_INITIALS_RE.search(text))))


def _is_subsequence(words: list[str], pwords: list[str]) -> bool:
    """`words` встречаются в `pwords` в том же порядке (пропуски разрешены)."""
    it = iter(pwords)
    return all(w in it for w in words)


# Длина основы для сравнения однословного сегмента со словом промпта (см. ниже).
_STEM_LEN = 5


def looks_like_prompt_echo(text: str, prompt: str | None) -> bool:
    """True, если распознанное — кусок самого `initial_prompt`, отданный обратно.

    Самый частый вид галлюцинации на этом материале (замер на реальной 107-секундной записи:
    больше половины ложных сегментов), и он прямо порождён нашей же настройкой: `WHISPER_PROMPT`
    задаёт домен («Протокол опроса. Интервьюер и опрашиваемый. Разговорная русская речь.»), но на
    не-речи декодеру нечего продолжать, кроме самого промпта, — и он выдаёт его дословно. Чем
    крупнее модель, тем послушнее она следует промпту и тем чаще это происходит: large-v3 эхает
    заметно чаще small, из-за чего переход на GPU и выглядел как «качество стало хуже».

    Проверяем так: все слова сегмента встречаются в промпте В ТОМ ЖЕ ПОРЯДКЕ (пропуски
    разрешены). Именно подпоследовательность, а не точное вхождение подряд: на живой записи эхо
    приходило и с выпавшим словом («Интервьюер и опрашиваемый. Разговорная речь.» при промпте
    «...Разговорная русская речь»), и строгое сравнение его пропускало. Живая реплика так
    совпасть не может: для этого она должна целиком состоять из слов промпта, идущих по порядку.
    Отброшенное не теряется — фонограмма пишется всегда.

    Отдельно — ОДНО слово, совпадающее с словом промпта лишь основой («опрос»/«опросы» против
    «опроса» в промпте). Русский язык склоняет, и эхо промпта приходит в другой форме: на живой
    записи именно так проскочили два последних ложных сегмента, когда точное сравнение уже
    отсекло остальные. Правило намеренно ограничено одним словом: выбросить односложный обрывок,
    совпавший с темой промпта, дешевле, чем оставить выдуманное слово в протоколе опроса,
    а вот резать так целые фразы было бы уже опасно."""
    if not prompt or not text:
        return False
    words = [w for w in (_normalize_word(w) for w in text.split()) if w]
    pwords = [w for w in (_normalize_word(w) for w in prompt.split()) if w]
    if not words or len(words) > len(pwords):
        return False
    if len(words) >= 2 and _is_subsequence(words, pwords):
        return True
    if len(words) == 1 and len(words[0]) >= _STEM_LEN:
        stem = words[0][:_STEM_LEN]
        return any(len(pw) >= _STEM_LEN and pw[:_STEM_LEN] == stem for pw in pwords)
    return False


def hallucination_reason(text: str, prompt: str | None) -> str | None:
    """Какой из трёх фильтров забракует `text`, или None. Один порядок проверок на все точки
    вызова (провайдер, live-сессия, пакетный проход) — чтобы в аудите было видно ИМЕННО
    сработавший фильтр, а не просто факт исчезновения реплики."""
    if not text:
        return None
    if has_repeating_ngram(text):
        return "повтор"
    if looks_like_prompt_echo(text, prompt):
        return "эхо промпта"
    if looks_like_known_hallucination(text):
        return "титры"
    return None


def dropped_note(where: str, reason: str, text: str) -> str:
    """Единая строка аудита отбраковки. Раньше выброшенное не оставляло никакого следа: в
    юридически значимом протоколе реплика просто исчезала, и разобрать постфактум, был это шум
    или живая речь, было нечем. Фильтры намеренно не смягчаем (размен взвешен в докстрингах
    выше) — закрываем именно молчаливость."""
    return f"[фильтр] {where}: отброшено ({reason}) — {text!r}"


